#!/usr/bin/env python3
"""Makes the files of a GitHub release from a bitstream: the core package, the ROM disk images,
Kiselev's licence, the checksums and the release notes.

Usage: python -B scripts/release/make_release.py --version V [--date YYYY-MM-DD]
       (--bitstream ap_core.rbf | --bitstream-zip <core zip>) --out DIR [--notes-in FILE] --notes-out FILE

  --version        the release version (tag v<version>): digits a.b.c, optionally -suffix
  --date           the release date; default the date of the heading "## <version> (<date>)" of
                   CHANGELOG.md; when given it is used as it is and the notes say "date given by hand"
  --bitstream      the Quartus build's ap_core.rbf
  --bitstream-zip  a core zip of an earlier run (the re-run of CI): its
                   Cores/BarabashkaD.Radio86RK/bitstream.rbf_r, bit-reversed back
  --out            a new or empty folder; it gets exactly the release assets
  --notes-in       the release notes so far (the draft's body); kept up to the marker line
  --notes-out      the merged release notes (outside --out)

Release assets (asset_names): BarabashkaD.Radio86RK_<version>_<date>.zip (package.py, the only
.zip), romdisk-1.bin .. romdisk-5.bin (package.game_disks), card.bin (card.build: Kiselev's ROM disk
and the five game disks), fatcard.bin (fatcard.build_card), romdisk-LICENSE.txt (from build/assets),
SHA256SUMS.txt (sha256sum format: every other asset, sorted). Kiselev's romdisk.bin is linked, not
attached. The notes: the text of --notes-in up to the marker line MARKER, then the marker and the
generated block (files with size and SHA256, Kiselev's link, install steps, the note for 0.8.2
users, the source commit, the bitstream, the CHANGELOG link); a re-run replaces only that block.

Every check runs before anything is built (version, date, bitstream, --out and the notes files,
mtools, the fetched assets, the core submodule, git); a failure prints one line on stderr and exits
1. A bitstream below MIN_BITSTREAM (1 MB) is a stand-in: refused unless the version contains
-ci-test. The notes say where the bitstream came from (bitstream_origin). The package is made in a
private folder inside --out, removed at the end; --notes-out is written through a temporary file
and os.replace. On success one line on stdout: "release: version V date D source <commit>
bitstream <SHA256 of ap_core.rbf>". The same inputs give the same bytes whatever the time zone
(fatcard.bin included: fixed FAT times, and the OEM name bytes 06-0A fixed rather than mformat's
version text; its other bytes as mformat writes them, checked against the layout); the zip only
with the same zlib build (package.write_zip), so a local zip and the CI zip may differ. Needs
mtools, python -B scripts/fetch_assets.py and the core submodule; no network.
"""
import argparse
import contextlib
import hashlib
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
for _sub in ('romdisk', 'fatcard', ''):
    sys.path.insert(0, os.path.join(ROOT, 'scripts', _sub))
import build_romdisks  # noqa: E402
import card  # noqa: E402
import fatcard  # noqa: E402
import package  # noqa: E402

ASSETS = os.path.join(ROOT, 'build', 'assets')
CHANGELOG = os.path.join(ROOT, 'CHANGELOG.md')
MARKER = '<!-- release assets (generated by CI) -->'
CORE_ZIP_BITSTREAM = 'Cores/%s/bitstream.rbf_r' % package.CORE_ID
GAME_DISKS = tuple('romdisk-%d.bin' % n for n in range(1, 6))
CARD = 'card.bin'
LICENCE = 'romdisk-LICENSE.txt'
SUMS = 'SHA256SUMS.txt'
FIXED_ASSETS = GAME_DISKS + (CARD, fatcard.CARD_IMAGE, LICENCE, SUMS)   # with the core zip: the release set
ZIP_PATTERN = package.CORE_ID + '_*.zip'
VERSION = re.compile(r'[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z][0-9A-Za-z.-]*)?')   # ASCII digits only
CI_TEST = '-ci-test'             # a test version: the only one that may take a stand-in bitstream
MIN_BITSTREAM = 1048576          # a real ap_core.rbf is a few MB; a smaller one is a stand-in
WORK = '.release-work'           # the private folder inside --out


class Refusal(Exception):
    """A check failed: the one line to print."""


def zip_name(version, date):
    return '%s_%s_%s.zip' % (package.CORE_ID, version, date)


def asset_names(version, date):
    """The release assets, sorted: the core zip and FIXED_ASSETS."""
    return sorted((zip_name(version, date),) + FIXED_ASSETS)


def asset_list(out_dir):
    """The regular files in out_dir, sorted."""
    return sorted(n for n in os.listdir(out_dir) if os.path.isfile(os.path.join(out_dir, n)))


def version_problem(version):
    """None for a version usable in a tag and a file name (VERSION, at most 31 characters, as
    core.json allows), else the reason."""
    if not VERSION.fullmatch(version or ''):
        return 'version %r is not a.b.c or a.b.c-suffix (digits; suffix of A-Z a-z 0-9 . -)' % version
    if len(version) > 31:
        return 'version %r longer than 31 characters (core.json)' % version
    return None


def changelog_date(text, version):
    """The date of the one heading "## <version> (<YYYY-MM-DD>)" of CHANGELOG.md; ValueError when
    there is none, more than one, or the date is not a calendar date."""
    pattern = re.compile(r'^## ' + re.escape(version) + r' \(([0-9]{4}-[0-9]{2}-[0-9]{2})\)$', re.M)
    found = pattern.findall(text.replace('\r\n', '\n'))
    if len(found) != 1:
        raise ValueError("CHANGELOG.md: %s heading '## %s (YYYY-MM-DD)' (exactly one needed)"
                         % ('no' if not found else '%d of the' % len(found), version))
    if not package.is_iso_date(found[0]):
        raise ValueError('CHANGELOG.md: ## %s (%s): not a calendar date' % (version, found[0]))
    return found[0]


def heading_anchor(heading):
    """GitHub's anchor of a Markdown heading: lower case, punctuation but - and _ dropped, spaces to -."""
    return re.sub(r'[^\w\- ]', '', heading.strip().lower()).replace(' ', '-')


def notes_intro():
    return ('_Everything from the marker line above to the end is generated by '
            '`scripts/release/make_release.py` and replaced on every run; write the summary above it._')


def merge_notes(existing, block):
    """existing (the draft's body; None or '' when empty) up to its first MARKER line, its trailing
    blank lines dropped, then one blank line, MARKER and block. CRLF becomes LF; a MARKER line at
    the start of block is not doubled. merge_notes(merge_notes(x, b), b) == merge_notes(x, b)."""
    lines = (existing or '').replace('\r\n', '\n').replace('\r', '\n').split('\n')
    if MARKER in (line.strip() for line in lines):
        lines = lines[:[line.strip() for line in lines].index(MARKER)]
    kept = '\n'.join(lines).rstrip()
    body = block.replace('\r\n', '\n').strip('\n')
    if body.split('\n', 1)[0].strip() == MARKER:
        body = body.split('\n', 1)[1].strip('\n') if '\n' in body else ''
    return (kept + '\n\n' if kept else '') + MARKER + '\n' + body + '\n'


def build_line(ci, dirty):
    """Who built the files: CI or a local run; a dirty tree is named."""
    if ci:
        text = ('Images, package and checksums built by CI (GitHub Actions) from this commit and the '
                'uploaded bitstream.')
    else:
        text = 'Images, package and checksums built locally (not by CI) from this commit.'
    if dirty:
        text += ' The tree had uncommitted changes: the files may differ from the commit.'
    return text


def _sha(data):
    return hashlib.sha256(data).hexdigest()


def _read(path):
    with open(path, 'rb') as f:
        return f.read()


def _inside(path, folder):
    try:
        return os.path.commonpath([os.path.normcase(path), os.path.normcase(folder)]) == os.path.normcase(folder)
    except ValueError:              # Windows: another drive
        return False


def read_bitstream(a):
    """ap_core.rbf as bytes, from --bitstream or from the core zip of --bitstream-zip."""
    if a.bitstream:
        name = os.path.basename(a.bitstream)
        if not os.path.isfile(a.bitstream):
            raise Refusal('bitstream %s missing' % name)
        try:
            data = _read(a.bitstream)
        except OSError as e:
            raise Refusal('bitstream %s not readable: %s' % (name, e.__class__.__name__))
        if not data:
            raise Refusal('bitstream %s is empty' % name)
        return data
    name = os.path.basename(a.bitstream_zip)
    if not os.path.isfile(a.bitstream_zip):
        raise Refusal('core zip %s missing' % name)
    try:
        with zipfile.ZipFile(a.bitstream_zip) as z:
            found = [n for n in z.namelist() if n == CORE_ZIP_BITSTREAM]
            if len(found) != 1:
                raise Refusal('core zip %s holds %d %s (1 expected)' % (name, len(found), CORE_ZIP_BITSTREAM))
            data = z.read(CORE_ZIP_BITSTREAM)
    except zipfile.BadZipFile:
        raise Refusal('core zip %s is not a zip file' % name)
    except (zlib.error, OSError, EOFError, NotImplementedError, RuntimeError) as e:
        raise Refusal('core zip %s: %s not readable (%s)' % (name, CORE_ZIP_BITSTREAM, e.__class__.__name__))
    if not data:
        raise Refusal('core zip %s: %s is empty' % (name, CORE_ZIP_BITSTREAM))
    return package.reverse_bits(data)


def fetched(entry, size=None):
    """A file of build/assets checked against its package/assets.json entry."""
    name = entry['name']
    path = os.path.join(ASSETS, name)
    if not os.path.isfile(path):
        raise Refusal('%s missing: run python -B scripts/fetch_assets.py' % name)
    data = _read(path)
    if _sha(data) != entry['sha256'] or (size is not None and len(data) != size):
        raise Refusal('%s does not match package/assets.json: run python -B scripts/fetch_assets.py' % name)
    return data


def git(*args):
    try:
        r = subprocess.run(['git', '-C', ROOT] + list(args), capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as e:
        raise Refusal('git %s: %s' % (args[0], e.__class__.__name__))
    if r.returncode != 0:
        raise Refusal('git %s failed: the release needs a git checkout of the repository' % args[0])
    return r.stdout


def prepare(a):
    """Every check, nothing written: a dict of what the build needs, or Refusal."""
    problem = version_problem(a.version)
    if problem:
        raise Refusal(problem)
    try:
        with open(CHANGELOG, encoding='utf-8') as f:
            changes = f.read()
    except (OSError, UnicodeError) as e:
        raise Refusal('CHANGELOG.md not readable: %s' % e.__class__.__name__)
    if a.date is not None:
        if not package.is_iso_date(a.date):
            raise Refusal('--date %r is not a calendar date YYYY-MM-DD' % a.date)
        date, by_hand = a.date, True
    else:
        try:
            date = changelog_date(changes, a.version)
        except ValueError as e:
            raise Refusal('%s; or give --date' % e)
        by_hand = False
    bitstream = read_bitstream(a)
    if len(bitstream) < MIN_BITSTREAM and CI_TEST not in a.version:
        raise Refusal('bitstream of %d bytes, below %d: not a Quartus ap_core.rbf (a stand-in only with a '
                      '%s version)' % (len(bitstream), MIN_BITSTREAM, CI_TEST))
    out = os.path.abspath(a.out)
    if os.path.exists(out) and (not os.path.isdir(out) or os.listdir(out)):
        raise Refusal('--out %s exists and is not an empty folder' % os.path.basename(out))
    notes_out = os.path.abspath(a.notes_out)
    if _inside(notes_out, out):
        raise Refusal('--notes-out must lie outside --out (the folder holds only the release assets)')
    if not os.path.isdir(os.path.dirname(notes_out)) or os.path.isdir(notes_out):
        raise Refusal('--notes-out %s: no such folder to write it in' % os.path.basename(notes_out))
    body = ''
    if a.notes_in is not None:
        if not os.path.isfile(a.notes_in):
            raise Refusal('--notes-in %s missing' % os.path.basename(a.notes_in))
        try:
            with open(a.notes_in, encoding='utf-8-sig') as f:
                body = f.read()
        except (OSError, UnicodeError) as e:
            raise Refusal('--notes-in %s not readable: %s' % (os.path.basename(a.notes_in), e.__class__.__name__))
    try:
        for tool in ('mformat', 'mcopy', 'mlabel'):
            fatcard.mtools(tool)
    except RuntimeError as e:
        raise Refusal(str(e).replace(os.environ.get('MTOOLS_DIR') or '\0', 'MTOOLS_DIR'))
    try:
        table = package.load_json(os.path.join(ROOT, 'package', 'assets.json'))
        rom_entry = next(x for x in table['assets'] if x['name'] == 'romdisk.bin')
        lic_entry = next(x for x in table['licences'] if x['name'] == LICENCE)
    except (OSError, ValueError, KeyError, StopIteration) as e:
        raise Refusal('package/assets.json: no romdisk.bin and %s entries (%s)' % (LICENCE, e.__class__.__name__))
    rom = fetched(rom_entry, rom_entry['size'])
    licence = fetched(lic_entry)
    if not os.path.isdir(package.PK_DIR) or not build_romdisks.pk_files(package.PK_DIR):
        raise Refusal("the core submodule's pk folder (the game tapes) is missing: "
                      'git submodule update --init --recursive')
    for part in ('roms/BIOS.BIN', 'roms/FONT.BIN', 'LICENSE.TXT'):
        if not os.path.isfile(os.path.join(package.CORE_SRC, *part.split('/'))):
            raise Refusal('the core submodule is missing src/%s: git submodule update --init --recursive' % part)
    commit = git('rev-parse', 'HEAD').strip()
    if not re.fullmatch(r'[0-9a-f]{40}', commit):
        raise Refusal('git rev-parse HEAD gave no commit')
    dirty = bool(git('status', '--porcelain').strip())
    return {'version': a.version, 'date': date, 'by_hand': by_hand, 'changes': changes, 'bitstream': bitstream,
            'out': out, 'notes_out': notes_out, 'body': body, 'table': table, 'rom': rom, 'rom_entry': rom_entry,
            'licence': licence, 'commit': commit, 'dirty': dirty, 'from_zip': a.bitstream_zip is not None,
            'ci': os.environ.get('GITHUB_ACTIONS') == 'true'}


def bitstream_origin(from_zip, ci):
    """Where the bitstream of the notes came from: the draft's core zip (a CI re-run), the draft's
    ap_core.rbf (CI), or a file given to a local run."""
    if from_zip:
        return 'taken from the core zip on the draft' if ci else 'taken from a core zip given locally'
    return 'uploaded to the draft' if ci else 'given locally'


def template_part(heading):
    """The body of '### <heading>' of README's ROM disk images section (the ROMDISKS.txt template),
    its wrapped lines joined (a GitHub release shows every line break)."""
    section = package.readme_section()
    start = section.index('### %s\n' % heading) + len('### %s\n' % heading)
    end = section.find('\n### ', start)
    lines = []
    for line in section[start:end if end >= 0 else len(section)].strip('\n').split('\n'):
        if lines and lines[-1] and line.strip() and not re.match(r'(- |\d+\. )', line.strip()):
            lines[-1] += ' ' + line.strip()
        else:
            lines.append(line.rstrip())
    return '\n'.join(lines)


def notes_block(c, files, disks, fat_files):
    """The generated part of the notes (below MARKER)."""
    repo = package.repo_url()
    kiselev = package.kiselev_romdisk()
    zip_file = zip_name(c['version'], c['date'])
    what = {zip_file: 'The core package: unzip it onto the SD card root.',
            CARD: 'J6 bank card with the card menu: Kiselev\'s ROM disk and the five game disks.',
            fatcard.CARD_IMAGE: 'J6 bank card with a FAT16 file system (8 MB): %d tape files and a file menu.'
                                % fat_files,
            LICENCE: 'Sergey Kiselev\'s GPL-3.0 licence (his ROM disk in `card.bin`, four of its programs in '
                     '`fatcard.bin`, the game disks\' menu loader derived from his).',
            SUMS: 'The SHA256 of every other file attached to the release (`sha256sum -c %s`).' % SUMS}
    for d in disks:
        what[d['file']] = 'Game disk %d (64 KB ROM disk): %d games.' % (d['disk'], len(d['entries']))
    order = [zip_file] + list(GAME_DISKS) + [CARD, fatcard.CARD_IMAGE, LICENCE, SUMS]
    rows = ['| `%s` | %s | %d | `%s` |' % (n, what[n], len(files[n]), _sha(files[n])) for n in order]
    try:
        anchor = '#' + heading_anchor('%s (%s)' % (c['version'], c['date'])) \
            if changelog_date(c['changes'], c['version']) == c['date'] else ''
    except ValueError:
        anchor = ''
    if c['by_hand']:
        dated = 'Release date %s: date given by hand (`--date`), not taken from CHANGELOG.md.' % c['date']
    else:
        dated = 'Release date %s: from the heading `## %s (%s)` of CHANGELOG.md.' % (c['date'], c['version'], c['date'])
    lines = [notes_intro(), '',
             '### Files', '',
             '| File | What it is | Size (bytes) | SHA256 |', '|---|---|---|---|'] + rows + [
             '',
             'Kiselev\'s ROM disk `romdisk.bin` is not attached as a file of its own (linked); `card.bin` contains '
             'it and `fatcard.bin` four programs from it, so Kiselev\'s licence is attached. Download `rom_disk.bin` '
             'from his repository and save it as `romdisk.bin`: %s (%s bytes, SHA256 `%s`; the file\'s page: %s).'
             % (kiselev['@ROMDISK_URL@'], kiselev['@ROMDISK_SIZE@'], kiselev['@ROMDISK_SHA256@'],
                kiselev['@ROMDISK_PAGE@']),
             '',
             '### Install', '',
             '1. Unzip `%s` onto the SD card root; the core appears as "Radio-86RK".' % zip_file,
             '2. Optional: the ROM disk images you want (the files above, Kiselev\'s `romdisk.bin`). '
             + template_part('Where to put them'), '',
             'How to load an image and start its menu: `ROMDISKS.txt` in that folder, or the '
             '[README](%s/blob/%s/README.md#rom-disk-images).' % (repo, c['commit']), '',
             '### Upgrading from 0.8.2', '',
             template_part('Upgrading from 0.8.2'), '',
             '### Build', '',
             '- Source: commit [`%s`](%s/commit/%s) of this repository.' % (c['commit'], repo, c['commit']),
             '- ' + build_line(c['ci'], c['dirty']),
             '- Bitstream `ap_core.rbf`: %d bytes, SHA256 `%s` (%s; the core package holds it bit-reversed as '
             '`bitstream.rbf_r`).' % (len(c['bitstream']), _sha(c['bitstream']),
                                      bitstream_origin(c['from_zip'], c['ci'])),
             '- ' + dated,
             '- Changes: [CHANGELOG.md](%s/blob/%s/CHANGELOG.md%s).' % (repo, c['commit'], anchor)]
    return '\n'.join(lines) + '\n'


def sha256sums(files):
    """SHA256SUMS.txt (sha256sum format, sorted by name, LF) of files {name: bytes}."""
    return ''.join('%s  %s\n' % (_sha(files[n]), n) for n in sorted(files))


def write_notes(path, notes):
    """notes (LF) to path through a temporary file in its folder and os.replace: the file is either
    the old one or complete."""
    fd, tmp = tempfile.mkstemp(prefix='.notes-', suffix='.tmp', dir=os.path.dirname(path))
    try:
        with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as f:
            f.write(notes)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.remove(tmp)
        raise


def make(c):
    """Builds every asset into c['out'] (empty) and the notes into c['notes_out']; returns the
    summary line. The work folder inside out is removed in any case."""
    out = c['out']
    work = os.path.join(out, WORK)
    files = {}

    def put(name, data):
        with open(os.path.join(out, name), 'wb') as f:
            f.write(data)
        files[name] = data

    os.makedirs(work)
    try:
        disks, games = package.game_disks(package.PK_DIR, {x['name'] for x in c['table']['assets']})
        if tuple(games) != GAME_DISKS:
            raise RuntimeError('game disks %s (%s expected)' % (list(games), list(GAME_DISKS)))
        for name in GAME_DISKS:
            put(name, games[name])
        image, _ = card.build([c['rom']] + [games[n] for n in GAME_DISKS], ['romdisk.bin'] + list(GAME_DISKS))
        put(CARD, image)
        meta = fatcard.build_card(os.path.join(work, 'fatcard'), package.PK_DIR, c['rom'])
        put(fatcard.CARD_IMAGE, _read(os.path.join(work, 'fatcard', fatcard.CARD_IMAGE)))
        stand = os.path.join(work, 'bitstream')
        os.makedirs(os.path.join(stand, 'output_files'))
        with open(os.path.join(stand, 'output_files', 'ap_core.rbf'), 'wb') as f:
            f.write(c['bitstream'])
        log = io.StringIO()
        with contextlib.redirect_stdout(log):
            rc = package.main(['--version', c['version'], '--date', c['date'], '--build', stand,
                               '--assets', ASSETS, '--output', os.path.join(work, 'package')])
        if rc != 0:
            errors = [line for line in log.getvalue().splitlines() if line.startswith('ERROR')]
            raise RuntimeError('package.py: %s' % (errors[0] if errors else 'exit %d' % rc))
        zip_file = zip_name(c['version'], c['date'])
        made = sorted(n for n in os.listdir(os.path.join(work, 'package')) if n.endswith('.zip'))
        if made != [zip_file]:
            raise RuntimeError('package.py made %s (%s expected)' % (made, zip_file))
        put(zip_file, _read(os.path.join(work, 'package', zip_file)))
        put(LICENCE, c['licence'])
        put(SUMS, sha256sums(files).encode('ascii'))
        notes = merge_notes(c['body'], notes_block(c, files, disks, len(meta['files'])))
    finally:
        shutil.rmtree(work, ignore_errors=True)
    if asset_list(out) != asset_names(c['version'], c['date']) or sorted(os.listdir(out)) != asset_list(out):
        raise RuntimeError('--out holds %s' % sorted(os.listdir(out)))
    write_notes(c['notes_out'], notes)
    return 'release: version %s date %s source %s bitstream %s' % (c['version'], c['date'], c['commit'],
                                                                   _sha(c['bitstream']))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--version', required=True)
    ap.add_argument('--date')
    source = ap.add_mutually_exclusive_group(required=True)
    source.add_argument('--bitstream')
    source.add_argument('--bitstream-zip')
    ap.add_argument('--out', required=True)
    ap.add_argument('--notes-in')
    ap.add_argument('--notes-out', required=True)
    a = ap.parse_args(argv)
    try:
        c = prepare(a)
    except Refusal as e:
        print('error: %s' % e, file=sys.stderr)
        return 1
    except Exception as e:                          # an unforeseen failure: still one line, nothing written
        print('error: %s' % one_line(e, os.path.abspath(a.out)), file=sys.stderr)
        return 1
    created = not os.path.exists(c['out'])
    try:
        os.makedirs(c['out'], exist_ok=True)
        line = make(c)
    except (Exception, SystemExit) as e:            # any failure (AsmError, EmuError, zlib.error, ...)
        try:
            for name in os.listdir(c['out']):
                path = os.path.join(c['out'], name)
                if name in asset_names(c['version'], c['date']) and os.path.isfile(path):
                    os.remove(path)
            if created and not os.listdir(c['out']):
                os.rmdir(c['out'])
        except OSError:
            pass
        print('error: %s' % one_line(e, c['out']), file=sys.stderr)
        return 1
    print(line)
    return 0


def one_line(e, out):
    """An exception as one line without local paths (--out as <out>, the repository as <repo>)."""
    if isinstance(e, SystemExit):
        text = str(e.code)
    elif isinstance(e, OSError) and e.strerror:     # the file's name only, never its path
        text = '%s: %s' % (e.strerror, os.path.basename(str(e.filename))) if e.filename else e.strerror
    elif isinstance(e, (ValueError, RuntimeError)) and str(e):
        text = str(e)
    else:
        text = '%s: %s' % (e.__class__.__name__, e) if str(e) else e.__class__.__name__
    text = text.replace(out, '<out>').replace(ROOT, '<repo>')
    return ' '.join(text.split('\n')[0].split()) or e.__class__.__name__


