class YamlError(ValueError):
    pass


def parse_yaml(text):
    """The YAML subset of the workflows: block mappings and sequences, plain and quoted scalars (kept
    as strings), literal block scalars (| and |-), comments, {} as an empty mapping. Anything else
    (other flow collections, anchors, aliases, tags, folded scalars, tabs, duplicate keys, a plain scalar with ': ') raises
    YamlError, so the guard never reads a file other than GitHub does without failing."""
    if '\t' in text:
        raise YamlError('tab character')
    lines = text.split('\n')
    pos = [0]
    key_line = re.compile(r'''([A-Za-z0-9_][A-Za-z0-9_.-]*|'[^']*'|"[^"\\]*") *:(?: +(.*)|)''')

    def where():
        return 'line %d' % (pos[0] + 1)

    def skip():
        while pos[0] < len(lines) and (not lines[pos[0]].strip() or lines[pos[0]].lstrip().startswith('#')):
            pos[0] += 1

    def indent(line):
        return len(line) - len(line.lstrip(' '))

    def node(min_indent):
        skip()
        if pos[0] >= len(lines) or indent(lines[pos[0]]) < min_indent:
            return None
        n = indent(lines[pos[0]])
        content = lines[pos[0]][n:]
        return sequence(n) if content == '-' or content.startswith('- ') else mapping(n)

    def scalar(s):
        if s[0] in '\'"':
            quote, i, chars = s[0], 1, []
            while True:
                if i >= len(s):
                    raise YamlError('%s: unterminated quoted scalar' % where())
                c = s[i]
                if quote == "'" and c == "'":
                    if s[i + 1:i + 2] == "'":
                        chars.append("'")
                        i += 2
                        continue
                    break
                if quote == '"' and c == '\\':
                    if s[i + 1:i + 2] not in ('"', '\\'):
                        raise YamlError('%s: escape not supported' % where())
                    chars.append(s[i + 1])
                    i += 2
                    continue
                if quote == '"' and c == '"':
                    break
                chars.append(c)
                i += 1
            rest = s[i + 1:].strip()
            if rest and not rest.startswith('#'):
                raise YamlError('%s: text after a quoted scalar' % where())
            return ''.join(chars)
        plain = s.split(' #')[0].strip()
        if plain == '{}':                       # the one flow form: an empty mapping (permissions: {})
            return {}
        if plain[0] in '[]{}&*!|>%@`,?' or ': ' in plain or plain.endswith(':'):
            raise YamlError('%s: not supported: %r' % (where(), plain))
        return plain

    def block(n, style):
        body = []
        while pos[0] < len(lines) and (not lines[pos[0]].strip() or indent(lines[pos[0]]) > n):
            body.append(lines[pos[0]])
            pos[0] += 1
        while body and not body[-1].strip():
            body.pop()
        if not body:
            return ''
        k = indent(next(line for line in body if line.strip()))
        if any(line.strip() and indent(line) < k for line in body):
            raise YamlError('%s: a block scalar line less indented than its first' % where())
        text = '\n'.join(line[k:] for line in body)
        return text + '\n' if style == '|' else text

    def value(rest, n):
        rest = rest.strip()
        if not rest or rest.startswith('#'):
            skip()
            if pos[0] < len(lines) and indent(lines[pos[0]]) > n:
                return node(n + 1)
            return None
        if rest in ('|', '|-'):
            return block(n, rest)
        return scalar(rest)

    def mapping(n):
        result = {}
        while True:
            skip()
            if pos[0] >= len(lines) or indent(lines[pos[0]]) < n:
                return result
            line = lines[pos[0]]
            if indent(line) > n:
                raise YamlError('%s: unexpected indentation' % where())
            m = key_line.fullmatch(line[n:])
            if not m:
                raise YamlError('%s: not a "key: value" line' % where())
            key = m.group(1)[1:-1] if m.group(1)[0] in '\'"' else m.group(1)
            if key in result:
                raise YamlError('%s: duplicate key %r' % (where(), key))
            pos[0] += 1
            result[key] = value(m.group(2) or '', n)

    def sequence(n):
        items = []
        while True:
            skip()
            if pos[0] >= len(lines) or indent(lines[pos[0]]) < n:
                return items
            line = lines[pos[0]]
            content = line[n:]
            if indent(line) > n or not (content == '-' or content.startswith('- ')):
                raise YamlError('%s: expected a sequence item' % where())
            item = content[1:]
            if key_line.fullmatch(item.strip()):        # "- key: value": a mapping starting on this line
                lines[pos[0]] = ' ' * (n + 1 + indent(item)) + item.strip()
                items.append(mapping(n + 1 + indent(item)))
            else:
                pos[0] += 1
                items.append(value(item, n))

    result = node(0)
    skip()
    if pos[0] < len(lines):
        raise YamlError('%s: text after the document' % where())
    return result


