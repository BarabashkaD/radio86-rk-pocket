class WorkflowGuard(unittest.TestCase):
    """release.yml passes the allow-list; each publish path, bypass or unlisted change fails it. The
    guard catches accidental edits; it is not a proof (the backstops: the environment release,
    main-only runs, immutable releases)."""

    @classmethod
    def setUpClass(cls):
        with open(WORKFLOW, encoding='utf-8', newline='') as f:
            cls.text = f.read()
        cls.mutated = {'script: ' + s: _in_script(cls.text, s) for s in SNIPPETS}
        cls.mutated.update({'change: ' + k: change(cls.text) for k, change in CHANGES.items()})
        scripts = []
        for text in [cls.text] + list(cls.mutated.values()):   # one pwsh run for every script of every variant
            try:
                wf = parse_yaml(text)
            except YamlError:
                continue
            for job in (wf.get('jobs') or {}).values():
                if isinstance(job, dict):
                    scripts += [s['run'] for s in job.get('steps') or [] if isinstance(s, dict)
                                and isinstance(s.get('run'), str)]
        pwsh_summaries(scripts)
        cls.base = collections.Counter(workflow_problems(cls.text))
        cls.jobs = parse_yaml(cls.text)['jobs']
        cls.write = [s['run'] for s in cls.jobs['write']['steps'] if 'run' in s][-1]
        cls.main = cls.write[cls.write.index('# Main\n'):]

    def test_the_workflow_passes(self):
        self.assertEqual(workflow_problems(self.text), [])
        wf = parse_yaml(self.text)
        self.assertEqual(list(wf['on']), ['workflow_dispatch'])
        self.assertEqual(wf['on']['workflow_dispatch']['inputs']['tag']['required'], 'true')
        self.assertEqual(wf['permissions'], {})
        jobs = self.jobs
        self.assertEqual(list(jobs), ['find', 'build', 'write'])
        for job in jobs.values():
            self.assertEqual((job['if'], job['runs-on']), (MAIN_ONLY, 'ubuntu-24.04'))
        self.assertEqual([jobs[j]['permissions'] for j in jobs],
                         [{'contents': 'write'}, {'contents': 'read'}, {'contents': 'write'}])
        self.assertEqual([jobs[j].get('environment') for j in jobs], [None, None, 'release'])
        self.assertEqual((jobs['build']['needs'], jobs['write']['needs']), ('find', ['find', 'build']))
        uses = {j: [s['uses'].split('@')[0] for s in jobs[j]['steps'] if 'uses' in s] for j in jobs}
        self.assertEqual(uses, {'find': ['actions/upload-artifact'],
                                'build': ['actions/download-artifact', 'actions/checkout', 'actions/setup-python',
                                          'actions/upload-artifact'],
                                'write': ['actions/download-artifact', 'actions/download-artifact']})
        for j in ('find', 'write'):             # the token's jobs: no profile, no repository code
            for step in jobs[j]['steps']:
                if 'run' in step:
                    self.assertEqual(step['shell'], NO_PROFILE_SHELL)
        texts = [command_text(c) for job in jobs.values()
                 for summary in pwsh_summaries([s['run'] for s in job['steps'] if 'run' in s])
                 for c in summary['commands']]
        for form, *_ in GH_FORMS:               # every allowed form is used: the list is not stale
            self.assertTrue(any(form.fullmatch(t) for t in texts), form.pattern)
        for forms in EXACT_COMMANDS.values():
            for form in forms:
                self.assertIn(form, texts)

    def test_the_token_only_where_gh_runs(self):
        with_gh = []
        for job_id, job in self.jobs.items():
            for step in job['steps']:
                env = step.get('env') or {}
                if 'uses' in step:
                    self.assertEqual(env, {}, step['uses'])
                    continue
                summary = pwsh_summaries([step['run']])[0]
                if runs(summary, 'gh'):
                    with_gh.append(job_id)
                    self.assertEqual((env['GH_TOKEN'], env['GH_REPO']),
                                     ('${{ github.token }}', '${{ github.repository }}'))
                else:
                    self.assertFalse({'GH_TOKEN', 'GH_REPO'} & set(env), step['name'])
        self.assertEqual(with_gh, ['find', 'find', 'write'])
        build = self.jobs['build']
        self.assertNotIn('GH_TOKEN', str(build))

    def test_the_last_writes_come_last(self):
        # nothing changes before the zip check; uploads checked before a stale core zip goes; the
        # notes after that; ap_core.rbf last, by its id
        main = self.main
        steps = ('the rebuilt core zip differs', 'Add-Asset ', 'Confirm-Assets', 'Remove-Asset $stale', 'Confirm-Zip',
                 'TEST BUILD: never publish this release.', 'gh api -X PATCH', 'Remove-Asset $env:RBF_ID')
        for step in steps:
            self.assertEqual(main.count(step), 1, step)
        order = [main.index(x) for x in steps]
        self.assertEqual(order, sorted(order))
        self.assertLess(main.index('the rebuilt core zip differs'), main.index('Remove-Asset'))
        self.assertNotIn('Remove-Asset', self.write[:self.write.index('# Main\n')].replace('function Remove-Asset', ''))
        # the notes edit: a fresh Get-Draft and the body comparison directly before it, no write in
        # between, its answer (id, draft, tag, target) checked on the next line
        code = [line.strip() for line in self.write.split('\n') if line.strip() and not line.strip().startswith('#')]
        self.assertEqual(notes_edit_problems(code), [])
        i = next(n for n, line in enumerate(code) if line.startswith('$edited = (gh api -X PATCH'))
        last = max(n for n in range(i) if code[n] == NOTES_EDIT_BEFORE[0])
        self.assertEqual(code[last + 1], NOTES_EDIT_BEFORE[1])
        self.assertFalse([line for line in code[last + 1:i] if WRITE_LINE.search(line)])
        self.assertEqual(code[i + 1], NOTES_EDIT_AFTER)

    def test_the_zip_path_never_deletes_the_only_bitstream(self):
        line = next(x for x in self.main.split('\n') if 'the rebuilt core zip differs' in x)
