"""Tests of the release script (scripts/release/make_release.py).

The full runs need mtools (MTOOLS_DIR or PATH), the core submodule and the fetched assets
(python -B scripts/fetch_assets.py); without them the tests fail with a hint, they never pass
silently. Two full runs in setUpClass: one from a stand-in bitstream (a -ci-test version, the only
kind that takes a bitstream below 1 MB), then one from the core zip of the first (the re-run of CI);
every asset must come out byte for byte the same, the notes but for where the bitstream came from. The time zone check
of fatcard.bin is in test_fatcard.py (fix_times).

WorkflowGuard: .github/workflows/release.yml against an allow-list (trigger, main-only jobs, their
permissions, the environment release on the writing job, actions, the token only on the steps that
call gh and never in the job that runs repository code, every command, member access, assignment
and variable of every script as the PowerShell parser sees it (scripts/tests/pwsh_ast.ps1, needs
pwsh): the seven GitHub API call forms, the other native commands whole, a few cmdlets in fixed
forms; the PATCH body, the draft check right before it and the check of its answer; the release
file names against make_release), with a self-test that feeds the checker each publish path or bypass and
expects a new problem. It catches accidental edits; it is not a proof. YamlSubset: the strict YAML
reader it uses.
"""
