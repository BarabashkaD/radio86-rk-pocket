def run(argv, env=None):
    """make_release.main in this process: (exit code, stdout lines, stderr lines)."""
    out, err = io.StringIO(), io.StringIO()
    with contextlib.ExitStack() as stack:
        if env is not None:
            stack.enter_context(mock.patch.dict(os.environ, env, clear=True))
        stack.enter_context(contextlib.redirect_stdout(out))
        stack.enter_context(contextlib.redirect_stderr(err))
        try:
            rc = make_release.main(argv)
        except SystemExit as e:
            rc = e.code
    return rc, out.getvalue().splitlines(), err.getvalue().splitlines()


def read(path):
    with open(path, 'rb') as f:
        return f.read()


def environment(**changes):
    env = {k: v for k, v in os.environ.items() if k not in ('TZ', 'GITHUB_ACTIONS')}
    env.update(changes)
    return env


class Notes(unittest.TestCase):
    BLOCK = 'Everything below is replaced by CI.\n\n| a | b |\n'

    def test_keeps_the_summary_and_appends_the_block_once(self):
        text = make_release.merge_notes('Summary\n\n- a change\n', self.BLOCK)
        self.assertEqual(text, 'Summary\n\n- a change\n\n' + MARKER + '\n' + self.BLOCK)
        self.assertEqual(text.count(MARKER), 1)

    def test_idempotent(self):
        once = make_release.merge_notes('Summary\n', self.BLOCK)
        thrice = make_release.merge_notes(make_release.merge_notes(once, self.BLOCK), self.BLOCK)
        self.assertEqual(thrice, once)

    def test_a_new_block_replaces_the_old(self):
        old = make_release.merge_notes('Summary\n', 'old table\n')
        new = make_release.merge_notes(old, 'new table\n')
        self.assertEqual(new, 'Summary\n\n' + MARKER + '\nnew table\n')
        self.assertNotIn('old table', new)

    def test_crlf_empty_and_missing_body(self):
        self.assertEqual(make_release.merge_notes('Summary\r\n\r\n- a\r\n', 'b\r\n'),
                         'Summary\n\n- a\n\n' + MARKER + '\nb\n')
        for body in ('', None, '\n\n', '\r\n'):
            self.assertEqual(make_release.merge_notes(body, 'b\n'), MARKER + '\nb\n', repr(body))

    def test_text_below_the_marker_is_replaced(self):
        body = 'Summary\n\n' + MARKER + '\nold block\n\nmaintainer text put below the marker\n'
        self.assertEqual(make_release.merge_notes(body, 'b\n'), 'Summary\n\n' + MARKER + '\nb\n')

    def test_the_block_says_it_is_replaced_by_ci(self):
        first = make_release.notes_intro()
        self.assertIn('replaced', first)
        self.assertIn('above', first)


class Changelog(unittest.TestCase):
    TEXT = ('# Changelog\n\n## Unreleased\n\n## 0.8.10 (2026-12-01)\n\n## 0.8.2 (2026-11-11)\n\n'
            '## 0.8.0 (not released on its own; in 0.8.1)\n\n## 0.6.3 (2026-11-09, not released)\n\n'
            '## 0.6.0 (pre-release, 2026-11-08)\n\n## 0.5.9 (2026-02-30)\n')

    def test_finds_the_date(self):
        self.assertEqual(make_release.changelog_date(self.TEXT, '0.8.2'), '2026-11-11')
        self.assertEqual(make_release.changelog_date(self.TEXT, '0.8.10'), '2026-12-01')
        self.assertEqual(make_release.changelog_date(self.TEXT.replace('\n', '\r\n'), '0.8.2'), '2026-11-11')

    def test_rejects(self):
        for version in ('0.8.1', '0.8', '0.8.0', '0.6.3', '0.6.0', '0.5.9', 'Unreleased', '9.9.9', '0.8.2 '):
            with self.assertRaises(ValueError, msg=version):
                make_release.changelog_date(self.TEXT, version)
        with self.assertRaises(ValueError):
            make_release.changelog_date(self.TEXT + '## 0.8.2 (2026-11-11)\n', '0.8.2')
        with self.assertRaises(ValueError):
            make_release.changelog_date('## 0.8.2 (2026-11-11) more\n', '0.8.2')

    def test_the_real_changelog(self):
        with open(os.path.join(ROOT, 'CHANGELOG.md'), encoding='utf-8') as f:
            self.assertEqual(make_release.changelog_date(f.read(), '0.8.2'), '2026-11-11')

    def test_anchor(self):
        self.assertEqual(make_release.heading_anchor('0.8.3 (2026-11-20)'), '083-2026-11-20')
        self.assertEqual(make_release.heading_anchor('0.0.0-ci-test (2000-01-01)'), '000-ci-test-2000-01-01')


