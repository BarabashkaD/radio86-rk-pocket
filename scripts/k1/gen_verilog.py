#!/usr/bin/env python3
"""Writes fpga/rtl/pocket_k1_layout.vh, the K1 key table as Verilog functions, from layout.py.

Usage: python -B scripts/k1/gen_verilog.py [--out PATH]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import layout  # noqa: E402

OUT = os.path.join(layout.ROOT, 'fpga', 'rtl', 'pocket_k1_layout.vh')
FONTS = {None: 0, '8': 1, '4': 2}


def label_word(font, codes):
    c = list(codes) + [0] * (3 - len(codes))
    return FONTS[font] << 23 | len(codes) << 21 | c[0] << 14 | c[1] << 7 | c[2]


def by_id(name, width, value):
    lines = ['function [%d:0] %s(input [6:0] id);' % (width - 1, name), '    begin case(id)']
    for k in layout.KEYS:
        lines.append("        7'd%d:%s=%d'd%d;" % (k.id, name, width, value(k)))
    lines += ["        default:%s=%d'd0;" % (name, width), '    endcase end', 'endfunction']
    return lines


def by_row(name, value):
    lines = ['function [6:0] %s(input [2:0] row);' % name, '    begin case(row)']
    for r in range(layout.ROWS):
        lines.append("        3'd%d:%s=7'd%d;" % (r, name, value(layout.row_keys(r))))
    lines += ["        default:%s=7'd0;" % name, '    endcase end', 'endfunction']
    return lines


def key_at():
    lines = ['function [6:0] k1_key_at(input [2:0] row,input [5:0] xq);', '    begin', "        k1_key_at=7'd0;",
             '        case(row)']
    for r in range(layout.ROWS):
        runs = []
        for xq in range(layout.QUARTERS):
            i = layout.key_at(r, xq)
            if runs and runs[-1][1] == i:
                runs[-1][0] = xq + 1
            else:
                runs.append([xq + 1, i])
        conds = ["if(xq<6'd%d)k1_key_at=7'd%d;" % (end, i) for end, i in runs[:-1]] + ["k1_key_at=7'd%d;" % runs[-1][1]]
        lines.append("        3'd%d: %s" % (r, ' else '.join(conds)))
    lines += ['        default:;', '        endcase', '    end', 'endfunction']
    return lines


def label():
    lines = ['function [24:0] k1_label(input [6:0] id,input rus,input sh,input ct);',
             '    begin', "        k1_label=25'd0;", '        case(id)']
    for k in layout.KEYS:
        words = [label_word(*layout.label(k, c >> 2 & 1, c >> 1 & 1, c & 1)) for c in range(8)]
        if len(set(words)) == 1:
            lines.append("        7'd%d:k1_label=25'h%07x;" % (k.id, words[0]))
        else:
            lines.append("        7'd%d:case({rus,sh,ct}) %s endcase" % (
                k.id, ' '.join("3'd%d:k1_label=25'h%07x;" % (c, w) for c, w in enumerate(words))))
    lines += ['        default:;', '        endcase', '    end', 'endfunction']
    return lines


def lit_ctrl():
    lines = ['function k1_lit_ctrl(input [6:0] id,input rus,input sh);', '    begin', "        k1_lit_ctrl=1'b0;",
             '        case(id)']
    for k in layout.KEYS:
        bits = [int(layout.lit_by_ctrl(k, c >> 1 & 1, c & 1)) for c in range(4)]
        if not any(bits):
            continue
        if all(bits):
            lines.append("        7'd%d:k1_lit_ctrl=1'b1;" % k.id)
        else:
            lines.append("        7'd%d:case({rus,sh}) %s default:; endcase" % (
                k.id, ' '.join("2'd%d:k1_lit_ctrl=1'b1;" % c for c, b in enumerate(bits) if b)))
    lines += ['        default:;', '        endcase', '    end', 'endfunction']
    return lines


def glyphs(name, width, table):
    lines = ['function [%d:0] %s(input [6:0] code);' % (width - 1, name), '    begin case(code)']
    for code in sorted(table):
        lines.append("        7'h%02x:%s=%d'b%s;" % (code, name, width, format(table[code], '0%db' % width)))
    lines += ["        default:%s=%d'd0;" % (name, width), '    endcase end', 'endfunction']
    return lines


def colours():
    """The colours of the two colour palettes (0 v1.1, 1 v1.4) and of the selected cap."""
    def word(cs):
        return ''.join('%06x' % c for c in cs)
    lines = ['function [95:0] k1_cap_set(input pal,input [2:0] role);', '    begin case({pal,role})']
    for p in (0, 1):
        pal = layout.PALETTES[p]
        for i, r in enumerate(layout.ROLES):
            lines.append("        4'd%d:k1_cap_set=96'h%s;" % (p * 8 + i, word(pal['sets'][pal['roles'][r]])))
    lines += ["        default:k1_cap_set=96'd0;", '    endcase end', 'endfunction']
    lines += ['function [47:0] k1_board(input pal);', "    k1_board=pal ? 48'h%s : 48'h%s;" % (
        word((layout.PALETTES[1]['pcb'], layout.PALETTES[1]['edge'])),
        word((layout.PALETTES[0]['pcb'], layout.PALETTES[0]['edge']))), 'endfunction']
    lines.append("localparam [95:0] K1_SELECTED_SET=96'h%s;" % word(layout.SELECTED))
    return lines


def generate():
    lines = [
        '// Generated by scripts/k1/gen_verilog.py from scripts/k1/layout.py (the K1 key table); do not edit.',
        '// Regenerate: python -B scripts/k1/gen_verilog.py',
        '// Key id 0..66, row by row, left to right. x, w, centre: quarter key units (1 unit = 20 px);',
        '// cap_x: cap left - panel left, cap_w: cap width, pixels. role: 0 a, 1 s, 2 e, 3 f, 4 c, 5 h, 6 p.',
        '// line: 0..63 matrix key (row*8+col), 64 SS (Shift), 65 US (Ctrl), 66 RUS/LAT.',
        '// k1_label = {font[1:0] (0 none, 1 6x8, 2 4x6), n[1:0], c0, c1, c2}: 6x8 codes are native_glyph',
        '// codes, except 08h and 18h, the new left / right arrows of k1_arrow_glyph (native_glyph is blank there, so',
        '// native_glyph(c) | k1_arrow_glyph(c) gives every 6x8 label glyph); 4x6 codes index k1_small_glyph.',
        '// Glyphs: MSB first, row by row (6x8: 48 bits, 4x6: 24 bits).',
        '// Colours (0xRRGGBB): k1_cap_set(pal, role) = {face, highlight, shadow, label} of palette pal (0 v1.1,',
        '// 1 v1.4); k1_board(pal) = {pcb, edge}; K1_SELECTED_SET = the selected cap. Mono is drawn by the RTL.',
    ]
    lines += by_id('k1_row', 3, lambda k: k.row)
    lines += by_id('k1_x', 6, lambda k: k.x)
    lines += by_id('k1_w', 5, lambda k: k.w)
    lines += by_id('k1_role', 3, lambda k: layout.ROLES.index(k.role))
    lines += by_id('k1_line', 7, lambda k: k.line)
    lines += by_id('k1_cap_x', 9, lambda k: layout.cap_rect(k)[0] - layout.PANEL[0])
    lines += by_id('k1_cap_w', 8, lambda k: layout.cap_rect(k)[2])
    lines += by_id('k1_centre', 6, lambda k: layout.centre_xq(k.id))
    lines += by_row('k1_row_first', lambda keys: keys[0].id)
    lines += by_row('k1_row_last', lambda keys: keys[-1].id)
    lines += key_at() + label() + lit_ctrl()
    lines += glyphs('k1_small_glyph', 24, layout.SMALL_GLYPHS)
    lines += glyphs('k1_arrow_glyph', 48, layout.ARROW_GLYPHS)
    lines += colours()
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--out', default=OUT)
    a = ap.parse_args()
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(generate())
    print('wrote %s' % a.out)


if __name__ == '__main__':
    main()
