; MENU OF THE FAT16 CARD FOR RADIO-86RK (ROM DISK ON THE SECOND 8255, A000H-BFFFH)
; SPDX-License-Identifier: BSD-3-Clause
; NEW CODE OF THIS REPOSITORY (LICENCE: LICENSE AT ITS ROOT); NOT DERIVED FROM KISELEV'S
; ROM_LOADER.ASM OR FROM ROM_LOADER_GAMES.ASM. RDCARD, CMPHD, SUBHD AND SELBK ARE LOADER.ASM'S,
; LINE FOR LINE (ASM8080 HAS NO INCLUDE; TEST_FATCARD.PY COMPARES THEM).
;
; RESERVED SECTORS 1-4 OF THE CARD. THE BOOT STAGE COPIES THEM TO 6C00H-73FFH AND JUMPS TO 6C00H
; WITH THE BOOT SECTOR (ITS BPB AT 000BH) STILL AT 0000H.
; RAM: 6C00H-71FFH CODE AND VARIABLES (MENUEND), 7200H-73FFH ONE ROOT DIRECTORY SECTOR (DIRBUF).
; THE STACK IS THE MONITOR'S (SP = 76CFH, AS G LEAVES IT; THE CALLS GO AT MOST ABOUT 20 BYTES DEEP,
; FAR ABOVE THE MONITOR'S VARIABLES 7600H-765FH). AT KEYWAIT THE STACK IS EMPTY, ALL STATE IS IN
; THE VARIABLES BELOW AND THE CARD IS ON BANK 0 (KEYNEXT; RESET KEEPS THE BANK).
; THE BPB IS READ ONCE, AT START, INTO THE VARIABLES; NOTHING READS 0000H-01FFH AFTERWARDS (Z ZEROES
; IT). THE LAYOUT: SECTOR S IS AT BANK S >> 7, OFFSET (S AND 127) * 512; CLUSTER C IS SECTOR
; DATASTART + C - 2 (1 SECTOR PER CLUSTER: THE BOOT STAGE CHECKED IT).
;
; LISTING (AS FATCARD.PY'S DIRECTORY()): THE ROOT DIRECTORY IN ORDER, UP TO THE FIRST NAME
; STARTING WITH 00H OR THE END OF THE ROOT; E5H (DELETED), ATTRIBUTE 0FH (LONG NAME) AND ATTRIBUTE
; BITS 1EH (HIDDEN, SYSTEM, LABEL, DIRECTORY) SKIPPED; AT MOST MAXN (520, 26 PAGES) FILES.
; A FILE IS RUNNABLE (AS FATCARD.PY'S MENU_ENTRIES()) WHEN ITS SIZE IS BELOW 64 KB, ITS FIRST
; CLUSTER IN 2..MAXCL, AND ITS FIRST 5 BYTES ARE A TAPE HEADER (OPTIONAL E6H, START, END, HIGH BYTE
; FIRST) WITH END >= START, END <= 73FFH, SIZE >= HEADER + END - START + 1. A RUNNABLE FILE SHOWS
; SSSS-EEEE, ANY OTHER "?"; THE RUN KEY ON A "?" LINE DOES NOTHING.
;
; SCREEN (PRINTS BY F818H ONLY; EVERY LINE AT MOST 63 CHARACTERS, SO THE MONITOR NEVER WRAPS, AND
; NOTHING SCROLLS):
;   ROW 0      RK86 CARD  <N> FILES  PAGE <P>/<Q>     (Q = CEIL(N / 20), 1 FOR N = 0)
;   ROW 1      A RULE OF 56 '-'
;   ROWS 2-21  ONE LINE PER FILE: MARKER, SPACE, NAME (8), SPACE, EXTENSION (3), 3 SPACES,
;              SSSS-EEEE OR "?"; A NAME BYTE OUTSIDE 20H-5FH SHOWS AS "?". N = 0: "  NO FILES".
;   ROW 22     THE RULE
;   ROW 23     THE KEYS, WITHOUT CR LF
; THE MARKER ">" IN COLUMN 0 OF THE SELECTED LINE IS PLACED WITH ESC Y (1BH, 'Y', 20H + ROW,
; 20H + COLUMN); THE MONITOR'S CURSOR THEN RESTS RIGHT OF IT.
; KEYS (THE CURSOR PRESET OF THE POCKET BUTTONS):
;   19H UP     THE LINE ABOVE; ON LINE 1 OF PAGE P > 1: PAGE P - 1, LINE 20; ON PAGE 1 LINE 1: NOTHING
;   1AH DOWN   THE LINE BELOW; ON THE LAST LINE OF A PAGE THAT IS NOT THE LAST: THE NEXT PAGE,
;              LINE 1; ON THE LAST FILE: NOTHING
;   18H RIGHT  THE NEXT PAGE, LINE 1; ON THE LAST PAGE NOTHING
;   08H LEFT   THE PREVIOUS PAGE, LINE 1; ON PAGE 1 NOTHING
;   0DH, 20H   RUN THE SELECTED FILE
;   5AH, 7AH   Z: ZERO 0000H-6BFFH (NO PRINT, NO REDRAW)
; UP AND DOWN INSIDE A PAGE REPRINT ONLY THE TWO MARKER CELLS; A PAGE CHANGE REDRAWS THE SCREEN
; (CLS 1FH FIRST). NO FILES: ONLY Z ACTS. ANY OTHER KEY: NOTHING.
; RUN: THE LOADER FROM RESERVED SECTOR 5 TO 7400H (RDCARD SELECTS BANK 0 FIRST, AS BEFORE EVERY
; FA68H), ITS PARAMETER BLOCK AT 7403H (FATSTART, DATASTART, CLUSTER, SIZE, MAXCL), JMP 7400H.
; ROUTINES: FA68H (HL..DE INCLUSIVE TO BC; CLOBBERS ALL), F818H (CLOBBERS A, C, HL), F803H (A = KEY).

PRINT:	EQU		0F818H	; MONITOR: PRINT THE STRING AT HL UP TO A 0 BYTE
GETCH:	EQU		0F803H	; MONITOR: WAIT FOR A KEY, A = ITS CODE
ROMCPY:	EQU		0FA68H	; MONITOR'S R: ROM DISK HL..DE TO RAM AT BC
MONSP:	EQU		76CFH	; THE MONITOR'S STACK, AS G LEAVES IT
PORTB:	EQU		0A001H	; SECOND 8255, PORT B
PORTC:	EQU		0A002H	; SECOND 8255, PORT C
PPICW:	EQU		0A003H	; SECOND 8255, CONTROL WORD
DIRBUF:	EQU		7200H	; ONE ROOT DIRECTORY SECTOR, 512 BYTES
LOADER:	EQU		7400H	; THE LOADER (LOADER.ASM), ITS ENTRY
LDRSEC:	EQU		5		; THE LOADER'S RESERVED SECTOR
FATSTART: EQU	7403H	; THE LOADER'S PARAMETER BLOCK (LOADER.ASM)
DATASTART: EQU	7405H
CLUSTER: EQU	7407H
SIZE:	EQU		7409H
MAXCL:	EQU		740BH
MAXN:	EQU		520		; AT MOST 26 PAGES OF 20 FILES
PGLEN:	EQU		20		; FILES PER PAGE
RULEN:	EQU		56		; LENGTH OF THE RULE
KUP:	EQU		19H
KDOWN:	EQU		1AH
KLEFT:	EQU		08H
KRIGHT:	EQU		18H

		ORG		6C00H
START:	LXI		SP,MONSP
; THE LAYOUT FROM THE BPB (THE BOOT STAGE CHECKED 512 BYTES PER SECTOR, 1 SECTOR PER CLUSTER, AT
; LEAST 6 RESERVED SECTORS, AT LEAST ONE FAT, TOTAL16 IN 1..4000H)
		LHLD	0EH		; RESERVED SECTORS: THE FIRST FAT
		SHLD	MFAT
		XCHG
		LDA		10H		; NUMBER OF FATS
		MOV		B,A
		LHLD	16H		; SECTORS PER FAT
		XCHG			; HL = RESERVED, DE = SECTORS PER FAT
RSTL:	DAD		D
		DCR		B
		JNZ		RSTL
		SHLD	RSTART	; THE FIRST ROOT SECTOR
		LHLD	11H		; ROOT ENTRIES
		LXI		D,15
		DAD		D		; CY:HL = ROOT ENTRIES + 15
		SBB		A
		ANI		1
		MOV		B,A		; B = THE CARRY
		MVI		C,4
RSHL:	DAD		H		; B:H:L = (CY:HL) SHIFTED LEFT BY 4
		MOV		A,B
		ADC		A
		MOV		B,A
		DCR		C
		JNZ		RSHL
		MOV		L,H
		MOV		H,B		; HL = (ROOT ENTRIES + 15) / 16
		SHLD	RSECS	; ROOT SECTORS
		XCHG
		LHLD	RSTART
		DAD		D
		SHLD	MDATA	; THE SECTOR OF CLUSTER 2
		XCHG
		LHLD	13H		; TOTAL SECTORS
		CALL	CMPHD	; CY: TOTAL < DATASTART
		JNC		MAXOK
		MOV		H,D
		MOV		L,E
MAXOK:	CALL	SUBHD
		INX		H
		SHLD	MMAX	; MAXCL = TOTAL - DATASTART + 1 (1: NO CLUSTER)
; COUNT THE FILES; NOTE THE ITERATOR STATE BEFORE THE FIRST FILE OF EACH PAGE
		LXI		H,0FFFFH
		SHLD	LOADED	; NO ROOT SECTOR IN DIRBUF
		INX		H
		SHLD	SECT
		SHLD	NFILES
		XRA		A
		STA		SLOT
		STA		NPAGES
		STA		KCNT
		STA		PAGE
		STA		LINE
CNTL:	LHLD	SECT
		SHLD	SVSECT
		LDA		SLOT
		STA		SVSLOT
		CALL	ITNEXT
		JC		NEWPG
		LDA		KCNT	; FILES LEFT ON THE CURRENT PAGE
		ORA		A
		JNZ		CNTK
		LDA		NPAGES	; THIS FILE STARTS A PAGE
		CALL	PGADR
		LXI		D,SVSECT
		MVI		B,3
		CALL	MOVB
		LXI		H,NPAGES
		INR		M
		MVI		A,PGLEN
CNTK:	DCR		A
		STA		KCNT
		LHLD	NFILES
		INX		H
		SHLD	NFILES
		LXI		D,MAXN
		CALL	CMPHD	; CY: NFILES < MAXN
		JC		CNTL

; THE KEY LOOP: EVERY KEY ENDS AT KEYNEXT, THEN KEYWAIT WITH THE STACK EMPTY. BANK 0 WHILE THE MENU
; WAITS: RESET KEEPS THE BANK, AND R0,1FF,0 THEN READS THE BOOT STAGE, NOT A ROOT OR FILE SECTOR.
NEWPG:	CALL	DRAW
KEYNEXT: XRA	A
		CALL	SELBK	; BANK 0
KEYWAIT: CALL	GETCH
		CPI		'Z'
		JZ		ZERO
		CPI		7AH		; 'Z' IN LOWER CASE
		JZ		ZERO
		MOV		B,A
		LDA		NPAGES	; NO FILES: ONLY Z ACTS
		ORA		A
		JZ		KEYNEXT
		MOV		A,B
		CPI		KDOWN
		JZ		DOWN
		CPI		KUP
		JZ		UP
		CPI		KRIGHT
		JZ		NEXTPG
		CPI		KLEFT
		JZ		LEFT
		CPI		0DH
		JZ		RUN
		CPI		' '
		JZ		RUN
		JMP		KEYNEXT

; Z: ZERO 0000H-6BFFH (THE MENU STARTS AT 6C00H)
ZERO:	LXI		H,0
ZLOOP:	MVI		M,0
		INX		H
		MOV		A,H
		CPI		6CH
		JC		ZLOOP
		JMP		KEYNEXT

DOWN:	LDA		LINES
		MOV		B,A
		LDA		LINE
		INR		A
		CMP		B
		JC		MOVETO	; LINE + 1 < LINES
NEXTPG:	LDA		NPAGES	; RIGHT, OR DOWN ON THE LAST LINE OF A PAGE
		MOV		B,A
		LDA		PAGE
		INR		A
		CMP		B
		JNC		KEYNEXT	; THE LAST PAGE
		STA		PAGE
		XRA		A
		STA		LINE
		JMP		NEWPG

UP:		LDA		LINE
		ORA		A
		JZ		UPPG
		DCR		A
		JMP		MOVETO
UPPG:	LDA		PAGE	; LINE 1: THE LAST LINE OF THE PREVIOUS PAGE
		ORA		A
		JZ		KEYNEXT
		DCR		A
		STA		PAGE
		MVI		A,PGLEN-1
		STA		LINE
		JMP		NEWPG

LEFT:	LDA		PAGE
		ORA		A
		JZ		KEYNEXT
		DCR		A
		STA		PAGE
		XRA		A
		STA		LINE
		JMP		NEWPG

; MOVETO: THE MARKER FROM LINE TO LINE A (ON THIS PAGE)
MOVETO:	PUSH	PSW
		MVI		A,' '
		CALL	MARK
		POP		PSW
		STA		LINE
		MVI		A,'>'
		CALL	MARK
		JMP		KEYNEXT

; RUN: THE SELECTED FILE FROM THE PAGE'S FIRST FILE ON (THE SAME ITERATOR AND CHECK AS THE
; DRAWING), THE LOADER, ITS PARAMETERS
RUN:	CALL	SEEKPG
		LDA		LINE
		INR		A
RUNL:	STA		DLINE
		CALL	ITNEXT
		JC		KEYNEXT	; (NOT REACHED: THE LINE HOLDS A FILE)
		LDA		DLINE
		DCR		A
		JNZ		RUNL	; HL = THE SELECTED ENTRY
		CALL	CHKENT
		ORA		A
		JZ		KEYNEXT	; A "?" LINE: NOTHING HAPPENS
		LXI		D,ECLUS
		LXI		H,MCLUS
		MVI		B,4
		CALL	MOVB	; ITS CLUSTER AND SIZE INTO THE PARAMETER IMAGE
		LXI		H,200H
		SHLD	CNT
		LXI		H,LDRSEC
		LXI		D,0
		LXI		B,LOADER
		CALL	RDCARD	; SELBK 0, THEN RESERVED SECTOR 5 TO 7400H
		LXI		D,MFAT
		LXI		H,FATSTART
		MVI		B,10
		CALL	MOVB	; THE PARAMETER BLOCK
		JMP		LOADER

; DRAW: THE WHOLE SCREEN FOR PAGE, THE MARKER ON LINE. CLOBBERS ALL.
DRAW:	LXI		H,LBUF
		SHLD	PTR
		MVI		A,1FH	; CLEAR THE SCREEN
		CALL	PUTC
		LXI		H,TITLE
		CALL	PUTS
		LHLD	NFILES
		CALL	DECW
		LXI		H,TPAGE
		CALL	PUTS
		LDA		PAGE
		INR		A
		CALL	DECA
		MVI		A,'/'
		CALL	PUTC
		LDA		NPAGES
		ORA		A
		JNZ		DRQ
		INR		A		; NO FILES: PAGE 1/1
DRQ:	CALL	DECA
		CALL	ENDLN
		CALL	RULE
		LHLD	NFILES	; LINES = MIN(20, NFILES - 20 * PAGE)
		LXI		D,PGLEN
		LDA		PAGE
		MOV		B,A
		INR		B
DRSUB:	DCR		B
		JZ		DRMIN
		CALL	SUBHD
		JMP		DRSUB
DRMIN:	CALL	CMPHD	; CY: HL < 20
		JC		DRLN
		MOV		L,E
DRLN:	MOV		A,L
		STA		LINES
		CALL	SEEKPG
		LDA		NPAGES
		ORA		A
		JNZ		DRTAB
		LXI		H,NOFMSG
		CALL	PUTS	; THE FIRST EMPTY LINE BELOW ENDS IT
DRTAB:	XRA		A
DRLOOP:	STA		DLINE
		LDA		LINES
		MOV		B,A
		LDA		DLINE
		CMP		B
		JNC		DRBLK	; NO FILE ON THIS LINE
		CALL	ITNEXT
		JC		DRBLK	; (NOT REACHED: THE COUNT SAW THESE FILES)
		CALL	ENTLN
		JMP		DRNXT
DRBLK:	CALL	ENDLN
DRNXT:	LDA		DLINE
		INR		A
		CPI		PGLEN
		JC		DRLOOP
		CALL	RULE
		LXI		H,FOOTER
		CALL	PRINT
		LDA		NPAGES
		ORA		A
		RZ
		MVI		A,'>'
		JMP		MARK

; ENTLN: THE LINE OF THE ENTRY AT HL (IN DIRBUF), PRINTED. CLOBBERS ALL.
ENTLN:	SHLD	EPTR
		MVI		A,' '
		CALL	PUTC
		CALL	PUTC
		MVI		B,8
		CALL	NAMEC	; HL = THE EXTENSION
		MVI		A,' '
		CALL	PUTC
		MVI		B,3
		CALL	NAMEC
		MVI		A,' '
		CALL	PUTC
		CALL	PUTC
		CALL	PUTC
		LHLD	EPTR
		CALL	CHKENT
		ORA		A
		JZ		ENTQ
		LHLD	ESTART
		CALL	HEXW
		MVI		A,'-'
		CALL	PUTC
		LHLD	EEND
		CALL	HEXW
		JMP		ENDLN
ENTQ:	MVI		A,'?'
		CALL	PUTC
		JMP		ENDLN

; NAMEC: B NAME BYTES FROM HL, A BYTE OUTSIDE 20H-5FH AS "?" (THE MONITOR WOULD TAKE 80H-9FH,
; MASKED WITH 7FH, AS CONTROL CODES). HL PAST THEM. CLOBBERS A, B.
NAMEC:	MOV		A,M
		CPI		20H
		JC		NAMEQ
		CPI		60H
		JC		NAMEOK
NAMEQ:	MVI		A,'?'
NAMEOK:	CALL	PUTC
		INX		H
		DCR		B
		JNZ		NAMEC
		RET

; CHKENT: THE ENTRY AT HL: ECLUS, ESIZE (THE LOW WORD); A = 1 RUNNABLE (THEN ESTART, EEND SET),
; ELSE 0. READS THE FILE'S FIRST 5 BYTES INTO HDR (NEVER INTO DIRBUF). CLOBBERS ALL.
CHKENT:	LXI		D,1AH
		DAD		D
		XCHG			; DE = THE FIRST CLUSTER FIELD
		LXI		H,ECLUS
		MVI		B,4
		CALL	MOVB	; ECLUS, ESIZE; DE = THE SIZE'S HIGH WORD
		XCHG
		MOV		A,M
		INX		H
		ORA		M
		JNZ		NOTRUN	; 64 KB OR MORE
		LHLD	ECLUS
		MOV		A,L
		SUI		2
		MOV		A,H
		SBI		0
		JC		NOTRUN	; CLUSTER < 2 (AN EMPTY FILE HAS 0)
		XCHG
		LHLD	MMAX
		CALL	CMPHD
		JC		NOTRUN	; MAXCL < CLUSTER
		LXI		H,5
		SHLD	CNT
		XCHG
		CALL	CLSEC
		LXI		D,0
		LXI		B,HDR
		CALL	RDCARD
		LXI		H,HDR
		MVI		B,4		; B = HEADER LENGTH, 4 WITHOUT E6H
		MOV		A,M
		CPI		0E6H
		JNZ		CHK4
		INX		H
		INR		B
CHK4:	MOV		D,M		; DE = START
		INX		H
		MOV		E,M
		INX		H
		MOV		A,M		; HL = END
		INX		H
		MOV		L,M
		MOV		H,A
		XCHG
		SHLD	ESTART
		XCHG
		SHLD	EEND
		CALL	CMPHD	; CY: END < START
		JC		NOTRUN
		MOV		A,H		; END <= 73FFH
		CPI		74H
		JNC		NOTRUN
		CALL	SUBHD	; T = END - START + 1 + HEADER, AT MOST 7405H
		INX		H
		MOV		E,B
		MVI		D,0
		DAD		D
		XCHG
		LHLD	ESIZE
		CALL	CMPHD	; CY: SIZE < T
		JC		NOTRUN
		MVI		A,1
		RET
NOTRUN:	XRA		A
		RET

; ITNEXT: THE NEXT LISTED ROOT ENTRY FROM THE ITERATOR STATE (SECT, SLOT). NC: HL = THE ENTRY IN
; DIRBUF, SLOT PAST IT. CY: THE END (A NAME STARTING 00H, OR NO ROOT SECTOR LEFT); THE STATE STAYS
; AT THE END. READS A ROOT SECTOR ONLY WHEN DIRBUF HOLDS ANOTHER ONE. CLOBBERS ALL.
ITNEXT:	LDA		SLOT
		CPI		16
		JC		ITLOAD
		XRA		A		; THE NEXT ROOT SECTOR
		STA		SLOT
		LHLD	SECT
		INX		H
		SHLD	SECT
ITLOAD:	LHLD	RSECS
		XCHG
		LHLD	SECT
		CALL	CMPHD	; CY: SECT < ROOT SECTORS
		JNC		ITEND
		XCHG			; DE = SECT
		LHLD	LOADED
		MOV		A,L
		CMP		E
		JNZ		ITREAD
		MOV		A,H
		CMP		D
		JZ		ITSCAN
ITREAD:	XCHG
		SHLD	LOADED
		XCHG
		LXI		H,200H
		SHLD	CNT
		LHLD	RSTART
		DAD		D		; HL = THE SECTOR
		LXI		D,0
		LXI		B,DIRBUF
		CALL	RDCARD
ITSCAN:	LDA		SLOT
		MOV		L,A
		MVI		H,0
		DAD		H
		DAD		H
		DAD		H
		DAD		H
		DAD		H
		LXI		D,DIRBUF
		DAD		D		; HL = DIRBUF + 32 * SLOT
		MOV		A,M
		ORA		A
		JZ		ITEND	; 00H: THE END OF THE DIRECTORY
		LDA		SLOT
		INR		A
		STA		SLOT
		MOV		A,M
		CPI		0E5H
		JZ		ITNEXT	; DELETED
		PUSH	H
		LXI		D,11
		DAD		D
		MOV		A,M		; THE ATTRIBUTE
		POP		H
		CPI		0FH
		JZ		ITNEXT	; LONG NAME
		ANI		1EH
		JNZ		ITNEXT	; HIDDEN, SYSTEM, LABEL, DIRECTORY
		RET				; NC FROM ANI
ITEND:	XRA		A
		SUI		1		; CY
		RET

; SEEKPG: THE ITERATOR TO THE STATE BEFORE THE FIRST FILE OF PAGE. CLOBBERS ALL.
SEEKPG:	LDA		PAGE
		CALL	PGADR
		LXI		D,SECT
		XCHG
		MVI		B,3
		JMP		MOVB

; PGADR: A = A PAGE -> HL = ITS ITERATOR STATE IN PSTART (3 BYTES). CLOBBERS DE.
PGADR:	MOV		L,A
		MVI		H,0
		MOV		D,H
		MOV		E,L
		DAD		H
		DAD		D
		LXI		D,PSTART
		DAD		D
		RET

; MARK: CHARACTER A IN COLUMN 0 OF LINE (ROW 2 + LINE), BY ESC Y. CLOBBERS A, C, HL.
MARK:	STA		MBUF+4
		LDA		LINE
		ADI		22H
		STA		MBUF+2
		LXI		H,MBUF
		JMP		PRINT

; PUTC: A INTO THE LINE BUFFER AT PTR, PTR + 1. KEEPS ALL BUT THE FLAGS.
PUTC:	PUSH	H
		LHLD	PTR
		MOV		M,A
		INX		H
		SHLD	PTR
		POP		H
		RET

; PUTS: THE STRING AT HL UP TO A 0 BYTE BY PUTC. CLOBBERS A, HL.
PUTS:	MOV		A,M
		ORA		A
		RZ
		CALL	PUTC
		INX		H
		JMP		PUTS

; ENDLN: CR LF, THEN PRINT THE LINE BUFFER AND EMPTY IT. CLOBBERS A, C, HL.
ENDLN:	MVI		A,0DH
		CALL	PUTC
		MVI		A,0AH
		CALL	PUTC
		XRA		A
		CALL	PUTC
		LXI		H,LBUF
		SHLD	PTR
		JMP		PRINT

; RULE: THE RULE AS ONE LINE. CLOBBERS A, B, C, HL.
RULE:	MVI		B,RULEN
RULEL:	MVI		A,'-'
		CALL	PUTC
		DCR		B
		JNZ		RULEL
		JMP		ENDLN

; DECA, DECW: A (DECA) OR HL (DECW, 0-999) IN DECIMAL WITHOUT LEADING ZEROS BY PUTC.
; CLOBBERS A, B, C, DE, HL.
DECA:	MOV		L,A
		MVI		H,0
DECW:	MVI		C,0		; C NOT 0: A DIGIT WAS PUT
		LXI		D,100
		CALL	DECDIG
		LXI		D,10
		CALL	DECDIG
		MOV		A,L
		ADI		'0'
		JMP		PUTC
DECDIG:	MVI		B,'0'	; B = THE DIGIT OF DE IN HL, HL = THE REST
DECL:	CALL	CMPHD
		JC		DECOUT
		CALL	SUBHD
		INR		B
		JMP		DECL
DECOUT:	MOV		A,B
		CPI		'0'
		JNZ		DECPUT
		INR		C
		DCR		C
		RZ				; A LEADING ZERO
DECPUT:	MVI		C,1
		JMP		PUTC

; HEXW: HL AS 4 HEX DIGITS BY PUTC. HEXB: A AS 2. CLOBBERS A, HL.
HEXW:	PUSH	H
		MOV		A,H
		CALL	HEXB
		POP		H
		MOV		A,L
HEXB:	PUSH	PSW
		MOV		L,A
		MVI		H,0
		DAD		H
		DAD		H
		DAD		H
		DAD		H		; H = A >> 4
		MOV		A,H
		CALL	HEXD
		POP		PSW
		ANI		0FH
HEXD:	CPI		10
		JC		HEXD1
		ADI		7
HEXD1:	ADI		'0'
		JMP		PUTC

; MOVB: B BYTES FROM DE TO HL; DE, HL PAST THEM. CLOBBERS A, B.
MOVB:	LDAX	D
		MOV		M,A
		INX		D
		INX		H
		DCR		B
		JNZ		MOVB
		RET

; CLSEC: HL = A CLUSTER -> HL = ITS SECTOR. CLOBBERS DE.
CLSEC:	XCHG
		LHLD	MDATA
		DAD		D
		DCX		H
		DCX		H
		RET

; RDCARD: CNT BYTES (1 TO 512 - DE) OF SECTOR HL (BELOW 8000H) FROM OFFSET DE TO RAM AT BC.
; DAD H GIVES H = THE BANK (SECTOR >> 7), L = THE HIGH BYTE OF THE SECTOR'S OFFSET IN THE BANK.
; SELBK BEFORE EVERY FA68H; ONE FA68H CALL INSIDE ONE SECTOR (FA68H RETURNS TO THE CALLER).
; CLOBBERS ALL.
RDCARD:	PUSH	B
		DAD		H
		MOV		A,H
		MOV		H,L
		MVI		L,0
		DAD		D		; HL = THE FIRST BYTE'S ADDRESS IN THE BANK
		PUSH	H
		CALL	SELBK
		LHLD	CNT
		DCX		H
		POP		D
		DAD		D		; HL = THE LAST BYTE'S ADDRESS
		XCHG
		POP		B
		JMP		ROMCPY

; CMPHD: CY = HL < DE (UNSIGNED). KEEPS HL, DE; CLOBBERS A.
CMPHD:	MOV		A,L
		SUB		E
		MOV		A,H
		SBB		D
		RET

; SUBHD: HL = HL - DE. CLOBBERS A.
SUBHD:	MOV		A,L
		SUB		E
		MOV		L,A
		MOV		A,H
		SBB		D
		MOV		H,A
		RET

; SELBK: SELECT BANK A (0-127) (BANK CARD SPEC 4.3, AS IN CARD_MENU.ASM). PORT C FF, PORT B = BANK,
; THEN PC7 RESET: PORT C FF TO 7F, THE CARD LATCHES PORT B. CLOBBERS A, B.
SELBK:	MOV		B,A
		MVI		A,90H	; MODE 0: A IN, B AND C OUT, ALL 00
		STA		PPICW
		MVI		A,0FFH
		STA		PORTC
		MOV		A,B
		STA		PORTB
		MVI		A,0EH	; BIT RESET PC7
		STA		PPICW
		RET

