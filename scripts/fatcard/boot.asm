; ROM_LOADER.ASM OR FROM ROM_LOADER_GAMES.ASM.
;
; SECTOR 0 OF THE CARD (BANK 0): MONITOR R0,1FF,0 THEN G0. BYTES 00-02 ARE MFORMAT'S EB 3C 90
; (ON THE 8080: XCHG, INR A, SUB B), 03-05 JMP START, 06-0A A FIXED OEM TEXT (FATCARD.PY), 0B-3D
; THE BPB (NOT WRITTEN HERE: FATCARD.PY INSTALLS ONLY 03-05 AND 3E-1FD OF THIS CODE), 1FE-1FF 55 AA.
; THE CARD IS STILL IN THE BANK THE BOOT SECTOR WAS JUST READ FROM (BANK 0): NO SELBK HERE.
; THE BPB IS CHECKED WHERE R PUT IT (000BH-0017H): 512 BYTES PER SECTOR, 1 SECTOR PER CLUSTER,
; AT LEAST 6 RESERVED SECTORS (0 BOOT, 1-4 MENU, 5 LOADER), AT LEAST ONE FAT, THE 16-BIT TOTAL
; SECTOR COUNT IN 1..4000H; ELSE "BAD CARD" AND THE MONITOR'S COMMAND LOOP. THEN RESERVED SECTORS 1-4
; (CARD 0200H-09FFH) TO 6C00H-73FFH BY FA68H AND JMP 6C00H: THE MENU READS THE BPB FROM 000BH.
; ROUTINES: FA68H (HL..DE INCLUSIVE TO BC; CLOBBERS ALL), F818H (CLOBBERS A, C, HL).

PRINT:	EQU		0F818H	; MONITOR: PRINT THE STRING AT HL UP TO A 0 BYTE
ROMCPY:	EQU		0FA68H	; MONITOR'S R: ROM DISK HL..DE TO RAM AT BC
MONITOR: EQU	0F86CH	; THE MONITOR'S COMMAND LOOP (LXI SP,76CFH; CHECKED IN BIOS.BIN)
MENU:	EQU		6C00H	; THE MENU: RESERVED SECTORS 1-4, 2048 BYTES

		ORG		3
		JMP		START

		ORG		3EH
START:	LHLD	0BH		; BYTES PER SECTOR: 0200H
		MOV		A,L
		ORA		A
		JNZ		BADCRD
		MOV		A,H
		CPI		2
		JNZ		BADCRD
		LDA		0DH		; SECTORS PER CLUSTER: 1
		CPI		1
		JNZ		BADCRD
		LHLD	0EH		; RESERVED SECTORS: AT LEAST 6
		MOV		A,H
		ORA		A
		JNZ		RSVOK
		MOV		A,L
		CPI		6
		JC		BADCRD
RSVOK:	LDA		10H		; NUMBER OF FATS: NOT 0
		ORA		A
		JZ		BADCRD
		LHLD	13H		; TOTAL SECTORS (16-BIT FIELD): NOT 0
		MOV		A,H
		ORA		L
		JZ		BADCRD
		MOV		A,L		; AT MOST 4000H: THE CARD REACHES SECTORS 0-16383 (128 BANKS)
		SUI		1
		MOV		A,H
		SBI		40H
		JNC		BADCRD	; NO BORROW: TOTAL - 4001H >= 0
		LXI		H,200H	; RESERVED SECTORS 1-4
		LXI		D,9FFH
		LXI		B,MENU
		CALL	ROMCPY
		JMP		MENU

BADCRD:	LXI		H,BADMSG
		CALL	PRINT
		JMP		MONITOR

BADMSG:	DB		0DH,0AH,"BAD CARD",0
BOOTEND:

		ORG		1FDH	; THE LAST BYTE BEFORE 55 AA: CODE REACHING IT FAILS AS "WRITTEN TWICE"
		DB		0

		END
