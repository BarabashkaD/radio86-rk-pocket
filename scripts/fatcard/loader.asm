; TAPE LOADER OF THE FAT16 CARD FOR RADIO-86RK (ROM DISK ON THE SECOND 8255, A000H-BFFFH)
; SPDX-License-Identifier: BSD-3-Clause
; NEW CODE OF THIS REPOSITORY (LICENCE: LICENSE AT ITS ROOT); NOT DERIVED FROM KISELEV'S
; ROM_LOADER.ASM OR FROM ROM_LOADER_GAMES.ASM.
;
; RESERVED SECTOR 5 OF THE CARD. THE MENU COPIES IT TO 7400H, FILLS THE PARAMETER BLOCK AT 7403H
; AND JUMPS TO 7400H. 7400H-75BFH CODE AND VARIABLES, 75C0H-75FFH THE STACK (SP = 7600H).
; THE FILE IS A TAPE: AN OPTIONAL E6H, START (HI, LO), END (HI, LO), THEN N = END - START + 1
; BYTES THAT GO TO START; ANYTHING AFTER THEM (A CHECKSUM) IS NOT READ. T = HEADER + N.
;
; ORDER: EVERYTHING IS CHECKED BEFORE THE FIRST BYTE OF RAM OUTSIDE THE LOADER IS WRITTEN:
;   CLUSTER IN 2..MAXCL (ELSE BAD FILE); THE 5 HEADER BYTES OF THE FIRST SECTOR; END >= START,
;   END <= 73FFH, SIZE >= T (ELSE NOT A TAPE; SIZE >= HEADER + 1 FOLLOWS FROM SIZE >= T AS N >= 1);
;   WALK WITH COPYF = 0: THE FAT CHAIN OF THE CEIL(T / 512) CLUSTERS THE LOAD NEEDS, EACH LINK BUT
;   THE LAST IN 2..MAXCL (ELSE BAD FILE; THE ENTRY OF THE LAST NEEDED CLUSTER IS NEVER READ).
;   A REFUSAL: SELBK 0, THE MESSAGE, THE MONITOR'S COMMAND LOOP.
; THEN CLS (THE LAST MONITOR PRINT), WALK WITH COPYF = 1 (THE SAME CHAIN, THE SAME VALUES: THE CARD
; IS A ROM, SO ITS CHKCL CANNOT FAIL; ONE FA68H CALL PER SECTOR, NEVER 0 BYTES: FA68H WITH
; DE = HL - 1 WOULD COPY 65536), SELBK 0, SP = 76CFH AS THE MONITOR'S G (FA5AH-FA61H) LEAVES IT,
; JUMP TO START.
; THE LAYOUT: 512-BYTE SECTORS, 1 SECTOR PER CLUSTER (THE BOOT STAGE CHECKS THE BPB); SECTOR S IS AT
; BANK S >> 7, OFFSET (S AND 127) * 512; CLUSTER C IS SECTOR DATASTART + C - 2.
; ROUTINES: FA68H (HL..DE INCLUSIVE TO BC; CLOBBERS ALL, NOTHING IS USED FROM ITS RESULT),
; F818H (CLOBBERS A, C, HL), SELBK (CLOBBERS A, B).

PRINT:	EQU		0F818H	; MONITOR: PRINT THE STRING AT HL UP TO A 0 BYTE
ROMCPY:	EQU		0FA68H	; MONITOR'S R: ROM DISK HL..DE TO RAM AT BC
MONITOR: EQU	0F86CH	; THE MONITOR'S COMMAND LOOP (LXI SP,76CFH; CHECKED IN BIOS.BIN)
MONSP:	EQU		76CFH	; THE MONITOR'S STACK, AS G LEAVES IT
STACK:	EQU		7600H	; THE LOADER'S STACK: 75C0H-75FFH
PORTB:	EQU		0A001H	; SECOND 8255, PORT B
PORTC:	EQU		0A002H	; SECOND 8255, PORT C
PPICW:	EQU		0A003H	; SECOND 8255, CONTROL WORD

		ORG		7400H
		JMP		ENTRY
; THE PARAMETER BLOCK, FILLED BY THE MENU (WORDS, LOW BYTE FIRST)
FATSTART: DW	0		; 7403H: SECTOR OF THE FIRST FAT
DATASTART: DW	0		; 7405H: SECTOR OF CLUSTER 2
CLUSTER: DW		0		; 7407H: FIRST CLUSTER OF THE FILE
SIZE:	DW		0		; 7409H: FILE SIZE (THE MENU REFUSES FILES OF 64 KB OR MORE)
MAXCL:	DW		0		; 740BH: THE LAST VALID CLUSTER (NUMBER OF CLUSTERS + 1)

ENTRY:	LXI		SP,STACK
		XRA		A		; CHECK FIRST, ALSO ON A SECOND G7400H (A LOAD LEAVES COPYF = 1)
		STA		COPYF
		LHLD	CLUSTER
		CALL	CHKCL
; THE HEADER: THE FIRST 5 BYTES OF THE FIRST SECTOR
		LXI		H,5
		SHLD	CNT
		LHLD	CLUSTER
		CALL	CLSEC
		LXI		D,0
		LXI		B,HDR
		CALL	RDCARD
		LXI		H,HDR
		MVI		B,4		; B = HEADER LENGTH, 4 WITHOUT E6H
		MOV		A,M
		CPI		0E6H
		JNZ		NOSYNC
		INX		H
		INR		B
NOSYNC:	MOV		A,B
		STA		HLEN
		MOV		D,M		; DE = START
		INX		H
		MOV		E,M
		INX		H
		MOV		A,M		; HL = END
		INX		H
		MOV		L,M
		MOV		H,A
		XCHG
		SHLD	TSTART
		XCHG
		CALL	CMPHD	; CY: END < START
		JC		NOTAPE
		MOV		A,H		; END <= 73FFH: THE LOADER, THE MONITOR'S VARIABLES, THE 8255S OUT OF REACH
		CPI		74H
		JNC		NOTAPE
		CALL	SUBHD	; T = END - START + 1 + HEADER, AT MOST 7405H: NO 16-BIT OVERFLOW
		INX		H
		MOV		E,B
		MVI		D,0
		DAD		D
		SHLD	TLEN
		XCHG
		LHLD	SIZE
		CALL	CMPHD	; CY: SIZE < T
		JC		NOTAPE
		CALL	WALK	; COPYF = 0: CHECK THE CHAIN
; THE COPY: NOTHING CAN FAIL FROM HERE ON
		LXI		H,CLSMSG
		CALL	PRINT
		LHLD	TSTART
		SHLD	DEST
		MVI		A,1
		STA		COPYF
		CALL	WALK
		XRA		A
		CALL	SELBK
		LXI		SP,MONSP
		LHLD	TSTART
		PCHL

; WALK: THE CLUSTERS OF THE FIRST T BYTES OF THE FILE. LEFT = THE BYTES OF T FROM THIS CLUSTER ON;
; THE PAYLOAD IN THIS CLUSTER RUNS FROM OFFSET DE (THE HEADER LENGTH, THEN 0) TO MIN(LEFT, 512).
; COPYF NOT 0: COPIES IT TO DEST. LEFT <= 512: THE LAST CLUSTER NEEDED, RETURN; ELSE ITS FAT
; ENTRY, CHECKED, IS THE NEXT CLUSTER. CLOBBERS ALL.
WALK:	LHLD	CLUSTER
		SHLD	CUR
		LHLD	TLEN
		SHLD	LEFT
		LDA		HLEN
		MOV		E,A
		MVI		D,0
WLOOP:	LDA		COPYF
		ORA		A
		JZ		WLAST
		LHLD	LEFT
		PUSH	D
		LXI		D,200H
		CALL	CMPHD	; CY: LEFT < 512
		JC		WLIM
		XCHG
WLIM:	POP		D
		CALL	SUBHD	; HL = MIN(LEFT, 512) - OFFSET: AT LEAST 1
		SHLD	CNT
		PUSH	D
		XCHG
		LHLD	DEST
		MOV		B,H
		MOV		C,L
		DAD		D
		SHLD	DEST
		LHLD	CUR
		CALL	CLSEC
		POP		D
		CALL	RDCARD
WLAST:	LHLD	LEFT
		LXI		D,201H
		CALL	CMPHD	; CY: LEFT <= 512
		RC
		LXI		D,0FE00H
		DAD		D		; LEFT - 512
		SHLD	LEFT
		LHLD	CUR
		CALL	NEXT
		CALL	CHKCL
		SHLD	CUR
		LXI		D,0
		JMP		WLOOP

; THE REFUSALS
NOTAPE:	LXI		H,NTMSG
		JMP		REFUSE
BADFIL:	LXI		H,BFMSG
REFUSE:	XRA		A
		CALL	SELBK	; KEEPS HL
		CALL	PRINT
		JMP		MONITOR

; CHKCL: BAD FILE UNLESS 2 <= HL <= MAXCL. KEEPS HL; CLOBBERS A, DE.
CHKCL:	MOV		A,L
		SUI		2
		MOV		A,H
		SBI		0
		JC		BADFIL	; HL < 2
		XCHG
		LHLD	MAXCL
		CALL	CMPHD	; CY: MAXCL < CLUSTER
		XCHG
		JC		BADFIL
		RET

; CLSEC: HL = A CLUSTER -> HL = ITS SECTOR. CLOBBERS DE.
CLSEC:	XCHG
		LHLD	DATASTART
		DAD		D
		DCX		H
		DCX		H
		RET

; NEXT: HL = A CLUSTER -> HL = ITS FAT ENTRY: SECTOR FATSTART + (CLUSTER >> 8), OFFSET
; 2 * (CLUSTER AND 0FFH); THE TWO BYTES NEVER CROSS A SECTOR. CLOBBERS ALL.
NEXT:	MOV		E,L
		MVI		D,0
		XCHG
		DAD		H		; HL = OFFSET IN THE FAT SECTOR, DE = CLUSTER
		XCHG
		MOV		L,H
		MVI		H,0
		PUSH	D
		XCHG
		LHLD	FATSTART
		DAD		D
		PUSH	H
		LXI		H,2
		SHLD	CNT
		POP		H		; HL = THE FAT SECTOR
		POP		D		; DE = THE OFFSET
		LXI		B,NEXTV
		CALL	RDCARD
		LHLD	NEXTV
		RET

; RDCARD: CNT BYTES (1 TO 512 - DE) OF SECTOR HL (BELOW 8000H) FROM OFFSET DE TO RAM AT BC.
; DAD H GIVES H = THE BANK (SECTOR >> 7), L = THE HIGH BYTE OF THE SECTOR'S OFFSET IN THE BANK.
; SELBK BEFORE EVERY FA68H; ONE FA68H CALL INSIDE ONE SECTOR (FA68H RETURNS TO THE CALLER).
; CLOBBERS ALL.
RDCARD:	PUSH	B
		DAD		H
		MOV		A,H
		MOV		H,L
		MVI		L,0
		DAD		D		; HL = THE FIRST BYTE'S ADDRESS IN THE BANK
		PUSH	H
		CALL	SELBK
		LHLD	CNT
		DCX		H
		POP		D
		DAD		D		; HL = THE LAST BYTE'S ADDRESS
		XCHG
		POP		B
		JMP		ROMCPY

; CMPHD: CY = HL < DE (UNSIGNED). KEEPS HL, DE; CLOBBERS A.
CMPHD:	MOV		A,L
		SUB		E
		MOV		A,H
		SBB		D
		RET

; SUBHD: HL = HL - DE. CLOBBERS A.
SUBHD:	MOV		A,L
		SUB		E
		MOV		L,A
		MOV		A,H
		SBB		D
		MOV		H,A
		RET

; SELBK: SELECT BANK A (0-127) (BANK CARD SPEC 4.3, AS IN CARD_MENU.ASM). PORT C FF, PORT B = BANK,
; THEN PC7 RESET: PORT C FF TO 7F, THE CARD LATCHES PORT B. CLOBBERS A, B.
SELBK:	MOV		B,A
		MVI		A,90H	; MODE 0: A IN, B AND C OUT, ALL 00
		STA		PPICW
		MVI		A,0FFH
		STA		PORTC
		MOV		A,B
		STA		PORTB
		MVI		A,0EH	; BIT RESET PC7
		STA		PPICW
		RET

NTMSG:	DB		0DH,0AH,"NOT A TAPE",0
BFMSG:	DB		0DH,0AH,"BAD FILE",0
CLSMSG:	DB		1FH,0

; VARIABLES
COPYF:	DB		0		; WALK: 0 CHECKS THE CHAIN, ELSE COPIES
HDR:	DB		0,0,0,0,0	; THE FIRST 5 BYTES OF THE FILE
HLEN:	DB		0		; HEADER LENGTH, 4 OR 5
TSTART:	DW		0		; TAPE START
TLEN:	DW		0		; T = HEADER + N
LEFT:	DW		0		; WALK: BYTES OF T FROM THE CURRENT CLUSTER ON
CUR:	DW		0		; WALK: THE CURRENT CLUSTER
DEST:	DW		0		; WALK: THE NEXT RAM ADDRESS OF THE PAYLOAD
CNT:	DW		0		; RDCARD: BYTES TO READ
NEXTV:	DW		0		; NEXT: THE FAT ENTRY READ
CODEND:

		END
