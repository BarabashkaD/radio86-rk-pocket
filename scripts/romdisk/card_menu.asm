; ROM_LOADER.ASM OR FROM ROM_LOADER_GAMES.ASM.
;
; THE FIRST 512 BYTES OF BANK 0 OF A CARD IMAGE (SCRIPTS/ROMDISK/CARD.PY FILLS IN THE TITLE,
; THE MENU LINES, THE KEY TABLE AND ITS LENGTH). MONITOR: R0,1FF,0 THEN G0.
; STAGE 1 RUNS AT 0000H: THE MONITOR'S R (FA68H) COPIES THESE 512 BYTES FROM THE CARD, STILL
; IN THE BANK THE MENU WAS JUST READ FROM (BANK 0), TO 7400H-75FFH; ONLY ITS JMP IS ABSOLUTE.
; THE MENU PRINTS ONE STRING AND WAITS FOR A KEY. THE KEY IS LOOKED UP IN KEYTAB: ENTRY N
; (FROM 0) IS DISK N, IN BANK N+1. A KEY NOT IN KEYTAB SHOWS THE MENU AGAIN. A KEY IN IT:
; SELBK (THE FULL SEQUENCE, MODE SET FIRST; NOTHING IS ASSUMED ABOUT PORTS B AND C), THEN THE
; DISK'S 0000H-01FFH TO 0000H BY FA68H AND JMP 0: THE DISK'S OWN LOADER, UNCHANGED.
; THE MONITOR'S STACK IS KEPT (SP IS NEVER SET).

PRINT:	EQU		0F818H	; MONITOR: PRINT THE STRING AT HL UP TO A 0 BYTE
GETCH:	EQU		0F803H	; MONITOR: WAIT FOR A KEY, ITS CODE IN A
ROMCPY:	EQU		0FA68H	; MONITOR'S R: ROM DISK HL..DE TO RAM AT BC
PORTB:	EQU		0A001H	; SECOND 8255, PORT B
PORTC:	EQU		0A002H	; SECOND 8255, PORT C
PPICW:	EQU		0A003H	; SECOND 8255, CONTROL WORD
NKEYS:	EQU		{count}	; NUMBER OF DISKS

		ORG		7400H
; STAGE 1, RUNNING AT 0000H
		LXI		H,0
		LXI		D,1FFH
		LXI		B,7400H
		CALL	ROMCPY
		JMP		MAIN

; THE MENU, RUNNING AT 7400H-75FFH
MAIN:	LXI		H,SCREEN
		CALL	PRINT
KEYWAIT: CALL	GETCH
		LXI		H,KEYTAB
		MVI		B,1		; BANK OF THE FIRST DISK
		MVI		C,NKEYS	; KEYS LEFT TO COMPARE
SCAN:	CMP		M
		JZ		FOUND
		INX		H
		INR		B
		DCR		C
		JNZ		SCAN
		JMP		MAIN	; NOT A DISK KEY
FOUND:	MOV		A,B		; A = BANK OF THE CHOSEN DISK
		CALL	SELBK
		LXI		H,0		; THE DISK'S LOADER: ITS 0000H-01FFH TO 0000H
		LXI		D,1FFH
		LXI		B,0
		CALL	ROMCPY
		JMP		0

; SELBK: SELECT BANK A (0-127). PORT C FF, PORT B = BANK, THEN PC7 RESET: PORT C FF TO 7F,
; THE CARD LATCHES PORT B. USES B.
SELBK:	MOV		B,A
		MVI		A,90H	; MODE 0: A IN, B AND C OUT, ALL 00
		STA		PPICW
		MVI		A,0FFH
		STA		PORTC
		MOV		A,B
		STA		PORTB
		MVI		A,0EH	; BIT RESET PC7
		STA		PPICW
		RET

KEYTAB:	DB		"{keys}"
SCREEN:	DB		1FH,"{title}"
{menu}
		DB		0
		ORG		75FFH
		DB		0FFH

		END
